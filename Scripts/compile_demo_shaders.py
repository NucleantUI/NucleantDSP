#!/usr/bin/env python3
"""Compile the demo's PyShader shaders (Demo/Shaders/*.py) to SPIR-V in
Demo/Sources/Synth/Shaders/, where the app loads them from its bundle.

    uv run Scripts/compile_demo_shaders.py

The .spv files are kept in the repository, as the Vult code is, so building
the demo — for macOS, iOS, Linux, Android or WebAssembly — needs no shader
compiler: PyShader's build plugin cannot run in a WebAssembly build (its
host tool needs SpirvTools' macOS library, which a WebAssembly build leaves
out).

The shaders import PyShader's standard library, which `uv sync` in Demo/
installs into Demo/.venv (Demo/pyproject.toml); pyshaderc finds it there.
pyshaderc itself is built from the sibling PyShader checkout when there is
one, else from PyShader on GitHub.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

PACKAGE_ROOT = Path(__file__).resolve().parent.parent
DEMO = PACKAGE_ROOT / "Demo"
SHADERS = DEMO / "Shaders"
OUTPUT = DEMO / "Sources" / "Synth" / "Shaders"
WORK = PACKAGE_ROOT / ".build" / "demo-shaders"
PYSHADER_URL = "https://github.com/NucleantUI/PyShader.git"


def swift() -> list[str]:
    """`swiftly run swift` where swiftly is installed, so the toolchain matches; else `swift`."""
    return ["swiftly", "run", "swift"] if shutil.which("swiftly") else ["swift"]


def pyshader_checkout() -> Path:
    """The sibling PyShader checkout, else PyShader's main branch, resolved here."""
    sibling = PACKAGE_ROOT.parent / "PyShader"
    if (sibling / "Package.swift").is_file():
        return sibling
    host = WORK / "pyshaderc-package"
    host.mkdir(parents=True, exist_ok=True)
    (host / "Package.swift").write_text(
        "// swift-tools-version: 6.3\n// Generated by Scripts/compile_demo_shaders.py: resolves PyShader.\n\n"
        "import PackageDescription\n\n"
        f'let package = Package(name: "PyShaderHost", dependencies: [.package(url: "{PYSHADER_URL}", branch: "main")], targets: [])\n')
    if subprocess.run([*swift(), "package", "resolve"], cwd=host).returncode != 0:
        sys.exit("error: resolving PyShader failed")
    return host / ".build" / "checkouts" / "PyShader"


def build_pyshaderc(checkout: Path) -> Path:
    scratch = WORK / "pyshaderc-build"
    command = [*swift(), "build", "--package-path", str(checkout), "--scratch-path", str(scratch),
               "--product", "pyshaderc", "-c", "release"]
    print("+", " ".join(command), flush=True)
    if subprocess.run(command).returncode != 0:
        sys.exit("error: building pyshaderc failed")
    bin_path = subprocess.run([*command, "--show-bin-path"], capture_output=True, text=True).stdout.strip()
    return Path(bin_path) / "pyshaderc"


def main() -> int:
    if shutil.which("uv") is None:
        sys.exit("error: uv not found; it installs the shaders' standard library")
    print("+ uv sync (Demo)", flush=True)
    if subprocess.run(["uv", "sync"], cwd=DEMO).returncode != 0:
        sys.exit("error: uv sync in Demo/ failed")

    pyshaderc = build_pyshaderc(pyshader_checkout())
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for source in sorted(SHADERS.glob("*.py")):
        output = OUTPUT / f"{source.stem}.spv"
        result = subprocess.run([str(pyshaderc), str(source), "-o", str(output), "--target", "compute"],
                                capture_output=True, text=True)
        if result.returncode != 0:
            sys.exit(f"error: compiling {source.relative_to(PACKAGE_ROOT)} failed:\n{result.stderr}")
        print(f"  {output.relative_to(PACKAGE_ROOT)}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
